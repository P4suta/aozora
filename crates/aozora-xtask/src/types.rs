//! Generates binding types and checks their consistency with wire schemas.

use std::collections::{BTreeMap, BTreeSet};
use std::env;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

use serde_json::{Map, Value};

use std::fmt::Write as _;

use aozora::json::SCHEMA_VERSION;
use aozora::{ContainerKind, DiagnosticSource, InternalCheckCode, NodeKind, PairKind, Severity};

use crate::TypesArgs;
use crate::TypesOp;
use crate::schema::SCHEMA_FILES;

const TYPES_REL_PATH: &str = "crates/aozora-wasm/types/aozora_types.d.ts";
const C_HEADER_REL_PATH: &str = "crates/aozora-ffi/include/aozora.h";
const JSON_SCHEMA_DIALECT: &str = "https://json-schema.org/draft/2020-12/schema";

pub(crate) fn dispatch(args: &TypesArgs) -> Result<(), String> {
    match args.op {
        TypesOp::Ts => dump(),
        TypesOp::Check => check(),
        TypesOp::Langs => langs_dump(),
        TypesOp::LangsCheck => langs_check(),
    }
}

fn workspace_root() -> Result<PathBuf, String> {
    let manifest_dir = env!("CARGO_MANIFEST_DIR");
    let root = Path::new(manifest_dir)
        .parent()
        .and_then(Path::parent)
        .ok_or_else(|| {
            format!("could not derive workspace root from CARGO_MANIFEST_DIR={manifest_dir:?}")
        })?;
    Ok(root.to_path_buf())
}

fn ts_string_union<T: Copy>(values: &[T], to_wire: impl Fn(T) -> &'static str) -> String {
    values
        .iter()
        .map(|v| format!("\"{}\"", to_wire(*v)))
        .collect::<Vec<_>>()
        .join(" | ")
}

fn push_export_type(out: &mut String, name: &str, union: &str) {
    out.push_str("export type ");
    out.push_str(name);
    out.push_str(" = ");
    out.push_str(union);
    out.push_str(";\n\n");
}

fn render() -> String {
    let mut out = String::new();
    render_header(&mut out);
    render_enums(&mut out);
    render_wire_payloads(&mut out);
    render_envelopes(&mut out);
    out
}

fn render_header(out: &mut String) {
    out.push_str("// AUTO-GENERATED by `xtask types ts` — DO NOT EDIT BY HAND.\n");
    out.push_str("// Regenerate with `just types` (or `xtask types ts`); commit the diff.\n");
    out.push_str("// Drift-gated in CI by `xtask types check`.\n");
    out.push('\n');
}

fn render_enums(out: &mut String) {
    out.push_str("// ─────────────────────────────────────────────────────────\n");
    out.push_str("// Enums (string-literal unions matching wire `kind` field)\n");
    out.push_str("// ─────────────────────────────────────────────────────────\n");
    out.push('\n');
    out.push_str("/** Cross-cutting tag for an AST node or `NodeRef` projection. */\n");
    push_export_type(
        out,
        "NodeKind",
        &ts_string_union(&NodeKind::ALL, NodeKind::as_json_tag),
    );
    out.push_str("/** Pair kind for `pairs_json` output. */\n");
    push_export_type(
        out,
        "PairKind",
        &ts_string_union(PairKind::ALL, PairKind::as_json_tag),
    );
    out.push_str("/** Container kind for `container_pairs` output. */\n");
    push_export_type(
        out,
        "ContainerKind",
        &ts_string_union(&ContainerKind::ALL, ContainerKind::as_str),
    );
    out.push_str("/** Diagnostic severity tier (wire field `severity`). */\n");
    push_export_type(
        out,
        "Severity",
        &ts_string_union(&Severity::ALL, Severity::as_json_str),
    );
    out.push_str(
        "/** Diagnostic origin (wire field `source`). `internal` indicates a library bug. */\n",
    );
    push_export_type(
        out,
        "DiagnosticSource",
        &ts_string_union(&DiagnosticSource::ALL, DiagnosticSource::as_json_str),
    );
    out.push_str("/** Stable namespaced ID for an Internal sanity-check failure. */\n");
    push_export_type(
        out,
        "InternalCheckCode",
        &ts_string_union(&InternalCheckCode::ALL, InternalCheckCode::as_code),
    );
}

fn render_wire_payloads(out: &mut String) {
    out.push_str("// ─────────────────────────────────────────────────────────\n");
    out.push_str("// Wire envelope payload types\n");
    out.push_str("// ─────────────────────────────────────────────────────────\n");
    out.push('\n');
    out.push_str(
        "/** Half-open UTF-8 byte span `[start, end)` in original source coordinates. */\n",
    );
    out.push_str("export interface Span {\n  start: number;\n  end: number;\n}\n\n");
    out.push_str("/** One source edit in pre-edit UTF-8 byte coordinates. */\n");
    out.push_str(
        "export interface TextEdit {\n  start: number;\n  end: number;\n  replacement: string;\n}\n\n",
    );
    out.push_str("/** One entry of `diagnostics` — `Diagnostic` projection. */\n");
    out.push_str(
        "export interface Diagnostic {\n  /** Variant tag (last segment of `Diagnostic::code()`, e.g. `\"source_contains_pua\"`). */\n  kind: string;\n  severity: Severity;\n  source: DiagnosticSource;\n  span: Span;\n  /** Unicode scalar value (only `SourceContainsPua` carries one today). */\n  codepoint?: number;\n}\n\n",
    );
    out.push_str("/** One entry of `nodes` — classified `Node` span in source coords. */\n");
    out.push_str("export interface Node {\n  kind: NodeKind;\n  span: Span;\n}\n\n");
    out.push_str("/** One entry of `pairs` — matched bracket pair link. */\n");
    out.push_str(
        "export interface Pair {\n  kind: PairKind;\n  open: Span;\n  close: Span;\n}\n\n",
    );
    out.push_str(
        "/** One entry of `container_pairs` — paired container in source coordinates. */\n",
    );
    out.push_str(
        "export interface ContainerPair {\n  kind: ContainerKind;\n  open: Span;\n  close: Span;\n}\n\n",
    );
    out.push_str("/** One resolved `※［＃…］` reference. */\n");
    out.push_str(
        "export interface GaijiResolution {\n  span: Span;\n  description: string;\n  mencode?: string;\n  codepoint?: number;\n  resolved?: string;\n}\n\n",
    );
    out.push_str("/** One completion-catalogue entry. */\n");
    out.push_str(
        "export interface Slug {\n  canonical: string;\n  family: string;\n  accepts_param: boolean;\n  doc: string;\n  partner?: string;\n}\n\n",
    );
}

fn render_envelopes(out: &mut String) {
    out.push_str("// ─────────────────────────────────────────────────────────\n");
    out.push_str("// Envelopes (top-level shape returned by every wire endpoint)\n");
    out.push_str("// ─────────────────────────────────────────────────────────\n");
    out.push('\n');
    out.push_str("/** Generic wire envelope. Every endpoint emits this top-level shape. */\n");
    write!(
        out,
        "export interface JsonEnvelope<T> {{\n  schemaVersion: {SCHEMA_VERSION};\n  data: ReadonlyArray<T>;\n}}\n\n",
    )
    .expect("writing to a String is infallible");
    out.push_str("export type DiagnosticsEnvelope    = JsonEnvelope<Diagnostic>;\n");
    out.push_str("export type NodesEnvelope          = JsonEnvelope<Node>;\n");
    out.push_str("export type PairsEnvelope          = JsonEnvelope<Pair>;\n");
    out.push_str("export type ContainerPairsEnvelope = JsonEnvelope<ContainerPair>;\n");
    out.push_str("export type GaijiEnvelope          = JsonEnvelope<GaijiResolution>;\n");
    out.push_str("export type SlugsEnvelope           = JsonEnvelope<Slug>;\n");
}

#[expect(
    clippy::print_stderr,
    reason = "the command reports results and diagnostics to developers"
)]
fn dump() -> Result<(), String> {
    let root = workspace_root()?;
    let path = root.join(TYPES_REL_PATH);
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent)
            .map_err(|err| format!("create_dir_all {}: {err}", parent.display()))?;
    }
    fs::write(&path, render())
        .map_err(|err| format!("write types artefact {}: {err}", path.display()))?;
    eprintln!("xtask types ts: wrote {}", path.display());
    Ok(())
}

#[expect(
    clippy::print_stderr,
    reason = "the command reports results and diagnostics to developers"
)]
fn check() -> Result<(), String> {
    let root = workspace_root()?;
    let path = root.join(TYPES_REL_PATH);
    let actual = render();
    let stored = fs::read_to_string(&path)
        .map_err(|err| format!("read types artefact {}: {err}", path.display()))?;
    let mut errors = Vec::new();
    if actual != stored {
        errors.push(format!(
            "TypeScript types drift detected in {TYPES_REL_PATH}: \
             run `xtask types ts` to regenerate, then commit"
        ));
    }
    if let Err(err) = check_payload_schema_parity(&root, &actual) {
        errors.push(err);
    }
    if errors.is_empty() {
        eprintln!("xtask types check: aozora_types.d.ts up to date and schema-consistent");
        Ok(())
    } else {
        Err(errors.join("\n"))
    }
}

struct SchemaFields {
    properties: BTreeSet<String>,
    required: BTreeSet<String>,
}

fn schema_field_shapes(root: &Path) -> Result<BTreeMap<String, SchemaFields>, String> {
    let mut shapes = BTreeMap::new();
    for (rel, _) in SCHEMA_FILES {
        let path = root.join(rel);
        let text =
            fs::read_to_string(&path).map_err(|err| format!("read {}: {err}", path.display()))?;
        let schema: Value = serde_json::from_str(&text)
            .map_err(|err| format!("parse {}: {err}", path.display()))?;
        if let Some(items) = schema
            .get("properties")
            .and_then(|p| p.get("data"))
            .and_then(|d| d.get("items"))
            && let Some(title) = items.get("title").and_then(Value::as_str)
        {
            insert_object_shape(title, items, &mut shapes);
        }
        if let Some(defs) = schema.get("$defs").and_then(Value::as_object) {
            for (key, def) in defs {
                insert_object_shape(key, def, &mut shapes);
            }
        }
    }
    Ok(shapes)
}

fn insert_object_shape(name: &str, obj: &Value, shapes: &mut BTreeMap<String, SchemaFields>) {
    let Some(props) = obj.get("properties").and_then(Value::as_object) else {
        return;
    };
    let properties = props.keys().cloned().collect();
    let required = obj
        .get("required")
        .and_then(Value::as_array)
        .map(|items| {
            items
                .iter()
                .filter_map(Value::as_str)
                .map(str::to_owned)
                .collect()
        })
        .unwrap_or_default();
    shapes.entry(name.to_owned()).or_insert(SchemaFields {
        properties,
        required,
    });
}

fn dts_interface_fields(dts: &str, name: &str) -> Option<BTreeMap<String, bool>> {
    let header = format!("export interface {name} {{");
    let after = &dts[dts.find(&header)? + header.len()..];
    let body = &after[..after.find("\n}")?];
    let mut fields = BTreeMap::new();
    for line in body.lines() {
        let line = line.trim();
        if line.is_empty() || line.starts_with('/') || line.starts_with('*') {
            continue;
        }
        let Some(colon) = line.find(':') else {
            continue;
        };
        let key = line[..colon].trim();
        let (key, optional) = key
            .strip_suffix('?')
            .map_or((key, false), |base| (base, true));
        if !key.is_empty() && key.chars().all(|c| c.is_ascii_alphanumeric() || c == '_') {
            fields.insert(key.to_owned(), optional);
        }
    }
    Some(fields)
}

const SCHEMA_MIRRORED_INTERFACES: &[(&str, &str)] = &[
    ("Span", "Span"),
    ("Diagnostic", "Diagnostic"),
    ("Node", "Node"),
    ("Pair", "Pair"),
    ("ContainerPair", "ContainerPair"),
    ("GaijiResolution", "GaijiResolution"),
    ("Slug", "Slug"),
];

fn check_payload_schema_parity(root: &Path, dts: &str) -> Result<(), String> {
    let shapes = schema_field_shapes(root)?;
    let mut problems = Vec::new();
    for (interface, title) in SCHEMA_MIRRORED_INTERFACES {
        let Some(shape) = shapes.get(*title) else {
            problems.push(format!(
                "no wire schema defines `{title}` to check interface `{interface}` against"
            ));
            continue;
        };
        let Some(fields) = dts_interface_fields(dts, interface) else {
            problems.push(format!("generated .d.ts has no `interface {interface}`"));
            continue;
        };
        let names: BTreeSet<String> = fields.keys().cloned().collect();
        for missing in shape.properties.difference(&names) {
            problems.push(format!(
                "interface `{interface}` is missing wire field `{missing}` (the schema has it)"
            ));
        }
        for extra in names.difference(&shape.properties) {
            problems.push(format!(
                "interface `{interface}` declares field `{extra}` absent from the schema"
            ));
        }
        for (field, &optional) in &fields {
            if !shape.properties.contains(field) {
                continue;
            }
            if optional == shape.required.contains(field) {
                problems.push(format!(
                    "interface `{interface}` field `{field}` is {} but the schema marks it {}",
                    if optional {
                        "optional (`?`)"
                    } else {
                        "required"
                    },
                    if shape.required.contains(field) {
                        "required"
                    } else {
                        "optional"
                    },
                ));
            }
        }
    }
    if problems.is_empty() {
        Ok(())
    } else {
        Err(format!(
            "TypeScript payload interfaces disagree with the wire JSON Schema:\n  {}\n  \
             -> if the schema is right (run `xtask schema check`), edit the interface in \
             `render_wire_payloads` to match",
            problems.join("\n  "),
        ))
    }
}

struct LangType {
    name: &'static str,
    quicktype_lang: &'static str,
    out: &'static str,
    comment: &'static str,
    prelude: &'static str,
    extra: &'static [&'static str],
    gofmt: bool,
}

const LANG_TYPES: &[LangType] = &[
    LangType {
        name: "go",
        quicktype_lang: "go",
        out: "crates/aozora-go/json_gen.go",
        comment: "// ",
        prelude: "package aozora\n\n",
        extra: &["--just-types", "--top-level", "AozoraJson"],
        gofmt: true,
    },
    LangType {
        name: "python",
        quicktype_lang: "py",
        out: "crates/aozora-py/python/aozora/wire_types.py",
        comment: "# ",
        prelude: "",
        extra: &["--python-version", "3.7", "--top-level", "AozoraJson"],
        gofmt: false,
    },
];

#[expect(
    clippy::print_stderr,
    reason = "the command reports results and diagnostics to developers"
)]
fn langs_dump() -> Result<(), String> {
    let root = workspace_root()?;
    let combined = write_combined_schema(&root)?;
    for lt in LANG_TYPES {
        let body = generate_lang(lt, &combined)?;
        let path = root.join(lt.out);
        if let Some(parent) = path.parent() {
            fs::create_dir_all(parent)
                .map_err(|err| format!("create_dir_all {}: {err}", parent.display()))?;
        }
        fs::write(&path, &body)
            .map_err(|err| format!("write {} types {}: {err}", lt.name, path.display()))?;
        eprintln!("xtask types langs: wrote {}", path.display());
    }
    let header_path = root.join(C_HEADER_REL_PATH);
    if let Some(parent) = header_path.parent() {
        fs::create_dir_all(parent)
            .map_err(|err| format!("create_dir_all {}: {err}", parent.display()))?;
    }
    fs::write(&header_path, generate_c_header(&root)?)
        .map_err(|err| format!("write C header {}: {err}", header_path.display()))?;
    eprintln!("xtask types langs: wrote {}", header_path.display());
    Ok(())
}

#[expect(
    clippy::print_stderr,
    reason = "the command reports results and diagnostics to developers"
)]
fn langs_check() -> Result<(), String> {
    let root = workspace_root()?;
    let combined = write_combined_schema(&root)?;
    let mut drift = Vec::new();
    for lt in LANG_TYPES {
        let actual = generate_lang(lt, &combined)?;
        let path = root.join(lt.out);
        let stored = fs::read_to_string(&path)
            .map_err(|err| format!("read {} types {}: {err}", lt.name, path.display()))?;
        if actual != stored {
            drift.push(lt.out.to_owned());
        }
    }
    let header_path = root.join(C_HEADER_REL_PATH);
    let actual = generate_c_header(&root)?;
    let stored = fs::read_to_string(&header_path)
        .map_err(|err| format!("read C header {}: {err}", header_path.display()))?;
    if actual != stored {
        drift.push(C_HEADER_REL_PATH.to_owned());
    }
    if drift.is_empty() {
        eprintln!("xtask types langs-check: generated host types and C header up to date");
        Ok(())
    } else {
        Err(format!(
            "per-language wire types drift detected in {} file(s):\n  {}\n\
             run `xtask types langs` to regenerate, then commit",
            drift.len(),
            drift.join("\n  "),
        ))
    }
}

/// A shared schema gives `quicktype` stable names for common types.
fn write_combined_schema(root: &Path) -> Result<PathBuf, String> {
    let mut defs = Map::new();
    let mut props = Map::new();
    for (rel, _) in SCHEMA_FILES {
        let path = root.join(rel);
        let text =
            fs::read_to_string(&path).map_err(|err| format!("read {}: {err}", path.display()))?;
        let schema: Value = serde_json::from_str(&text)
            .map_err(|err| format!("parse {}: {err}", path.display()))?;
        let obj = schema
            .as_object()
            .ok_or_else(|| format!("{}: schema root is not an object", path.display()))?;
        let env_title = obj
            .get("title")
            .and_then(Value::as_str)
            .ok_or_else(|| format!("{}: schema missing root title", path.display()))?
            .to_owned();
        if let Some(file_defs) = obj.get("$defs").and_then(Value::as_object) {
            for (key, value) in file_defs {
                defs.entry(key.clone()).or_insert_with(|| value.clone());
            }
        }
        let mut items = obj
            .get("properties")
            .and_then(|p| p.get("data"))
            .and_then(|d| d.get("items"))
            .cloned()
            .ok_or_else(|| format!("{}: missing properties.data.items", path.display()))?;
        let item_title = items
            .get("title")
            .and_then(Value::as_str)
            .ok_or_else(|| format!("{}: data.items missing title", path.display()))?
            .to_owned();
        if let Some(item_obj) = items.as_object_mut() {
            item_obj.remove("$schema");
            item_obj.remove("$defs");
        }
        defs.insert(item_title.clone(), items);
        defs.insert(
            env_title.clone(),
            serde_json::json!({
                "type": "object",
                "additionalProperties": false,
                "required": ["schemaVersion", "data"],
                "properties": {
                    "schemaVersion": { "type": "integer" },
                    "data": { "type": "array", "items": { "$ref": format!("#/$defs/{item_title}") } },
                },
            }),
        );
        props.insert(
            env_title.clone(),
            serde_json::json!({ "$ref": format!("#/$defs/{env_title}") }),
        );
    }
    for (key, value) in &mut defs {
        if let Some(value_obj) = value.as_object_mut() {
            value_obj.insert("title".to_owned(), Value::String(key.clone()));
        }
    }
    let combined = serde_json::json!({
        "$schema": JSON_SCHEMA_DIALECT,
        "title": "AozoraJson",
        "type": "object",
        "additionalProperties": false,
        "properties": props,
        "$defs": defs,
    });
    let combined_path = env::temp_dir().join("aozora_json_combined.schema.json");
    let pretty = serde_json::to_string_pretty(&combined).map_err(|err| err.to_string())?;
    fs::write(&combined_path, pretty)
        .map_err(|err| format!("write combined schema {}: {err}", combined_path.display()))?;
    Ok(combined_path)
}

fn generate_lang(lt: &LangType, combined_schema: &Path) -> Result<String, String> {
    let mut cmd = Command::new("quicktype");
    cmd.arg("--src-lang")
        .arg("schema")
        .arg("--lang")
        .arg(lt.quicktype_lang)
        .args(lt.extra)
        .arg(combined_schema);
    let output = cmd.output().map_err(|err| {
        format!(
            "failed to run quicktype ({err}); run `just setup`, then \
             use `just types-langs`"
        )
    })?;
    if !output.status.success() {
        return Err(format!(
            "quicktype failed for `{}`:\n{}",
            lt.name,
            String::from_utf8_lossy(&output.stderr)
        ));
    }
    let body = String::from_utf8(output.stdout)
        .map_err(|err| format!("quicktype output for `{}` not UTF-8: {err}", lt.name))?;
    let assembled = finalize(lt, &body);
    if lt.gofmt {
        gofmt(&assembled)
    } else if lt.name == "python" {
        strict_python(&assembled)
    } else {
        Ok(assembled)
    }
}

fn strict_python(source: &str) -> Result<String, String> {
    let import = "from typing import Any, List, Optional, TypeVar, Type, cast, Callable";
    let strict_import =
        "from typing import Any, Callable, Dict, List, Optional, Protocol, Type, TypeVar, cast";
    let to_class = "def to_class(c: Type[T], x: Any) -> dict:\n\
                    \x20   assert isinstance(x, c)\n\
                    \x20   return cast(Any, x).to_dict()";
    let strict_to_class = "class ToDict(Protocol):\n\
                           \x20   def to_dict(self) -> Dict[str, Any]: ...\n\
                           \n\
                           \n\
                           def to_class(c: Type[T], x: Any) -> Dict[str, Any]:\n\
                           \x20   assert isinstance(x, c)\n\
                           \x20   return cast(ToDict, x).to_dict()";
    let from_union = "def from_union(fs, x):\n\
                      \x20   for f in fs:\n\
                      \x20       try:\n\
                      \x20           return f(x)\n\
                      \x20       except:\n\
                      \x20           pass\n\
                      \x20   assert False";
    let strict_from_union = "def from_union(fs: List[Callable[[Any], Any]], x: Any) -> Any:\n\
         \x20   for f in fs:\n\
         \x20       try:\n\
         \x20           return f(x)\n\
         \x20       except (AssertionError, TypeError, ValueError):\n\
         \x20           pass\n\
         \x20   raise AssertionError";

    if !source.contains(import) || !source.contains(to_class) || !source.contains(from_union) {
        return Err("quicktype Python support prelude changed".to_owned());
    }
    Ok(source
        .replacen(import, strict_import, 1)
        .replacen(to_class, strict_to_class, 1)
        .replacen(from_union, strict_from_union, 1)
        .replace(" -> dict:", " -> Dict[str, Any]:")
        .replace("result: dict = {}", "result: Dict[str, Any] = {}"))
}

fn generate_c_header(root: &Path) -> Result<String, String> {
    let crate_dir = root.join("crates/aozora-ffi");
    let config = cbindgen::Config::from_file(crate_dir.join("cbindgen.toml"))
        .map_err(|err| format!("read cbindgen.toml: {err}"))?;
    let bindings = cbindgen::Builder::new()
        .with_crate(crate_dir)
        .with_config(config)
        .with_language(cbindgen::Language::C)
        .with_after_include(format!("#define AOZORA_SCHEMA_VERSION {SCHEMA_VERSION}"))
        .generate()
        .map_err(|err| format!("generate C header: {err}"))?;
    let mut bytes = Vec::new();
    bindings.write(&mut bytes);
    String::from_utf8(bytes).map_err(|err| format!("C header is not UTF-8: {err}"))
}

fn gofmt(src: &str) -> Result<String, String> {
    use std::io::Write as _;
    use std::process::Stdio;

    let mut child = Command::new("gofmt")
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .map_err(|err| format!("failed to run gofmt ({err}); run `just setup`"))?;
    child
        .stdin
        .take()
        .ok_or("gofmt: no stdin handle")?
        .write_all(src.as_bytes())
        .map_err(|err| format!("gofmt: write stdin: {err}"))?;
    let output = child
        .wait_with_output()
        .map_err(|err| format!("gofmt: wait: {err}"))?;
    if !output.status.success() {
        return Err(format!(
            "gofmt failed:\n{}",
            String::from_utf8_lossy(&output.stderr)
        ));
    }
    String::from_utf8(output.stdout).map_err(|err| format!("gofmt output not UTF-8: {err}"))
}

fn finalize(lt: &LangType, body: &str) -> String {
    let mut out = String::new();
    out.push_str(lt.comment);
    out.push_str(
        "AUTO-GENERATED by `xtask types langs` (quicktype, from the aozora wire JSON Schema).\n",
    );
    out.push_str(lt.comment);
    out.push_str(
        "DO NOT EDIT — regenerate with `just types-langs`; drift-gated by `just drift-gate`.\n",
    );
    out.push('\n');
    out.push_str(lt.prelude);
    if lt.name == "go" {
        writeln!(out, "const SchemaVersion = {SCHEMA_VERSION}\n")
            .expect("writing to a String is infallible");
    }
    for line in body.lines() {
        out.push_str(line.trim_end());
        out.push('\n');
    }
    out
}

